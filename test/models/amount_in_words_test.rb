require "test_helper"

class AmountInWordsTest < ActiveSupport::TestCase
  {
    0 => "Ноль рублей 00 копеек",
    1 => "Один рубль 00 копеек",
    22 => "Двадцать два рубля 00 копеек",
    111 => "Сто одиннадцать рублей 00 копеек",
    1001 => "Одна тысяча один рубль 00 копеек",
    2002.02 => "Две тысячи два рубля 02 копейки",
    5415 => "Пять тысяч четыреста пятнадцать рублей 00 копеек",
    1_000_000 => "Один миллион рублей 00 копеек",
    2_511_014.01 => "Два миллиона пятьсот одиннадцать тысяч четырнадцать рублей 01 копейка"
  }.each do |amount, words|
    test "#{amount} in words" do
      assert_equal words, AmountInWords.rubles(amount)
    end
  end
end
